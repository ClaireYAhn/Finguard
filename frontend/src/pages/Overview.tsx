import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Area, AreaChart, Bar, BarChart, CartesianGrid, Legend, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { api, errMsg } from '../api'
import { Callout, Empty, ErrorBox, PageHeader, SimBadge, Spinner, Status, Table, Th, TierChip, ACTION_COLORS } from '../components/ui'
import { pct, useFetch } from '../hooks'
import type { Overview as OV } from '../types'

const CARDS: [string, string][] = [
  ['requests', 'Requests'], ['blocked', 'Blocked'], ['modified', 'Modified'], ['escalated', 'Escalated'],
  ['open_reviews', 'Open reviews'], ['apps_live', 'Apps live'], ['apps_idle', 'Apps with no recent activity'],
]
const ATTN: Record<string, { icon: string; link: string; label: string }> = {
  rising_blocks: { icon: '📈', link: '/audit', label: 'Rising blocks' },
  unreviewed_escalations: { icon: '⚑', link: '/reviews', label: 'Unreviewed escalations' },
  disabled_rules: { icon: '⏸', link: '/policies', label: 'Disabled rules' },
  no_activity: { icon: '💤', link: '/apps', label: 'No activity' },
}

function heat(rate: number) {
  const r = Math.min(Math.max(rate, 0), 1)
  return `hsl(${Math.round(130 - 130 * Math.min(r * 3, 1))}, 70%, 82%)`
}

export default function Overview() {
  const [days, setDays] = useState(7)
  const [msg, setMsg] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)
  const [simCount, setSimCount] = useState(200)
  const ov = useFetch<OV>(`ov-${days}`, () => api(`/api/overview?days=${days}`), { interval: 15000 })
  const d = ov.data

  const act = async (path: string, body?: unknown, label?: string) => {
    setBusy(true)
    setMsg(`${label}…`)
    try {
      const r = await api(path, { method: 'POST', body })
      setMsg(path.includes('simulate') ? `Simulated traffic generated: ${r.sent} requests. ${r.note ?? ''}` : `Demo apps seeded: ${r.seeded}. ${r.note ?? ''}`)
      ov.reload()
    } catch (e) {
      setMsg(errMsg(e))
    } finally {
      setBusy(false)
    }
  }

  return (
    <div>
      <PageHeader title="Overview">
        <label htmlFor="days" className="text-sm font-medium">Period</label>
        <select id="days" className="input w-auto" value={days} onChange={(e) => setDays(Number(e.target.value))}>
          {[1, 7, 14, 30].map((n) => <option key={n} value={n}>{n === 1 ? 'Last 24 hours' : `Last ${n} days`}</option>)}
        </select>
      </PageHeader>

      {ov.error && <ErrorBox message={ov.error} onRetry={ov.reload} />}
      {ov.loading && <Spinner />}
      {d && (
        <>
          {d.simulated_share > 0 && (
            <div className="mb-4"><Callout tone="warn">
              <SimBadge /> <strong>{pct(d.simulated_share)}</strong> of the requests in this period ({d.simulated_requests}) are simulated traffic generated by the simulator, not real users.
            </Callout></div>
          )}

          <div className="mb-4 grid grid-cols-2 gap-3 md:grid-cols-4 xl:grid-cols-7">
            {CARDS.map(([k, label]) => (
              <div key={k} className="card"><div className="text-xs font-medium text-slate-700">{label}</div><div className="text-2xl font-bold text-navy-900">{d.cards[k] ?? 'n/a'}</div></div>
            ))}
          </div>

          <section className="card mb-4" aria-labelledby="gen">
            <h2 id="gen" className="mb-2 font-semibold">Generate data</h2>
            <p className="mb-2 text-sm text-slate-800">
              These buttons create <strong>simulated</strong> traffic (fictional users, backdated timestamps, channel &quot;simulated&quot;) that is sent through the real gateway. It is not real usage.
            </p>
            <div className="flex flex-wrap items-end gap-2">
              <div><label htmlFor="simc" className="label">Requests</label><input id="simc" type="number" min={1} max={1000} className="input w-24" value={simCount} onChange={(e) => setSimCount(Number(e.target.value))} /></div>
              <button type="button" className="btn-primary" disabled={busy || d.cards.apps_total === 0} onClick={() => void act('/api/simulate', { count: simCount, days }, 'Generating simulated traffic')}>Generate simulated traffic</button>
              {d.cards.apps_total === 0 && <button type="button" className="btn-secondary" disabled={busy} onClick={() => void act('/api/seed', undefined, 'Seeding demo apps')}>Seed demo apps</button>}
              {d.cards.apps_total > 0 && <button type="button" className="btn-secondary" disabled={busy} onClick={() => void act('/api/seed', undefined, 'Seeding demo apps')}>Seed demo apps (safe to repeat)</button>}
            </div>
            <Status>{msg}</Status>
          </section>

          {d.cards.requests === 0 ? (
            <Empty>No requests in this period yet. Seed demo apps, then generate simulated traffic, or route real traffic through the gateway.</Empty>
          ) : (
            <>
              <section className="card mb-4" aria-labelledby="ts">
                <h2 id="ts" className="mb-2 font-semibold">Requests over time ({d.bucket})</h2>
                <div className="h-64" role="img" aria-label="Stacked area chart of requests by action over time">
                  <ResponsiveContainer width="100%" height="100%">
                    <AreaChart data={d.series}>
                      <CartesianGrid strokeDasharray="3 3" />
                      <XAxis dataKey="t" tick={{ fontSize: 11 }} />
                      <YAxis allowDecimals={false} tick={{ fontSize: 11 }} />
                      <Tooltip /><Legend />
                      {(['allow', 'modify', 'block', 'escalate'] as const).map((k) => (
                        <Area key={k} type="monotone" dataKey={k} stackId="1" stroke={ACTION_COLORS[k]} fill={ACTION_COLORS[k]} fillOpacity={0.7} />
                      ))}
                    </AreaChart>
                  </ResponsiveContainer>
                </div>
              </section>

              <section className="card mb-4" aria-labelledby="heat">
                <h2 id="heat" className="mb-1 font-semibold">Risk heatmap</h2>
                <p className="mb-2 text-xs text-slate-700">Each cell is an app; the number is its violation rate (modified + blocked + escalated share of requests). Redder is higher.</p>
                {['high', 'limited', 'minimal'].map((tier) => {
                  const cells = d.heatmap.filter((h) => h.tier === tier)
                  return (
                    <div key={tier} className="mb-2 flex flex-wrap items-start gap-2">
                      <div className="w-24 pt-2"><TierChip tier={tier} /></div>
                      <div className="flex flex-1 flex-wrap gap-2">
                        {cells.length === 0 && <span className="pt-2 text-sm text-slate-700">No apps</span>}
                        {cells.map((c) => (
                          <div key={c.app} className="w-40 rounded-md border border-slate-400 p-2 text-slate-900" style={{ background: heat(c.violation_rate) }}>
                            <div className="truncate text-xs font-medium" title={c.app}>{c.app}</div>
                            <div className="text-lg font-bold">{pct(c.violation_rate)}</div>
                            <div className="text-xs">{c.requests} requests</div>
                          </div>
                        ))}
                      </div>
                    </div>
                  )
                })}
              </section>

              <div className="mb-4 grid gap-4 lg:grid-cols-2">
                <section className="card" aria-labelledby="perapp">
                  <h2 id="perapp" className="mb-2 font-semibold">Per app</h2>
                  <Table caption="Requests per app">
                    <thead><tr><Th>App</Th><Th>Tier</Th><Th>Requests</Th><Th>Blocked</Th><Th>Violation rate</Th></tr></thead>
                    <tbody className="divide-y divide-slate-200">
                      {d.per_app.map((a) => (
                        <tr key={a.app_id}>
                          <td className="td">{a.app}</td><td className="td"><TierChip tier={a.tier} /></td>
                          <td className="td">{a.requests}</td><td className="td">{a.blocked}</td>
                          <td className="td"><div className="flex items-center gap-2"><span className="w-14">{pct(a.violation_rate)}</span><span className="block h-2 w-24 rounded bg-slate-200" aria-hidden="true"><span className="block h-2 rounded bg-red-600" style={{ width: `${Math.min(a.violation_rate, 1) * 100}%` }} /></span></div></td>
                        </tr>
                      ))}
                    </tbody>
                  </Table>
                </section>
                <section className="card" aria-labelledby="perrule">
                  <h2 id="perrule" className="mb-2 font-semibold">Top rules fired</h2>
                  {d.per_rule.length === 0 ? <Empty>No rules fired in this period.</Empty> : (
                    <div className="h-72" role="img" aria-label="Bar chart of rules fired by outcome">
                      <ResponsiveContainer width="100%" height="100%">
                        <BarChart data={d.per_rule.slice(0, 10)} layout="vertical" margin={{ left: 30 }}>
                          <CartesianGrid strokeDasharray="3 3" />
                          <XAxis type="number" allowDecimals={false} /><YAxis type="category" dataKey="rule_id" width={110} tick={{ fontSize: 10 }} />
                          <Tooltip /><Legend />
                          <Bar dataKey="modified" stackId="a" fill={ACTION_COLORS.modify} />
                          <Bar dataKey="blocked" stackId="a" fill={ACTION_COLORS.block} />
                          <Bar dataKey="escalated" stackId="a" fill={ACTION_COLORS.escalate} />
                        </BarChart>
                      </ResponsiveContainer>
                    </div>
                  )}
                </section>
              </div>
            </>
          )}

          <section className="card" aria-labelledby="attn">
            <h2 id="attn" className="mb-2 font-semibold">Attention needed</h2>
            {d.attention.length === 0 ? <p className="text-sm">Nothing needs attention right now.</p> : (
              <ul className="space-y-2">
                {d.attention.map((a, i) => {
                  const m = ATTN[a.kind] || { icon: '!', link: '/', label: a.kind }
                  return (
                    <li key={i} className="flex flex-wrap items-center gap-2 rounded-md border border-slate-300 p-2 text-sm">
                      <span aria-hidden="true">{m.icon}</span><strong>{m.label}</strong><span>{a.app}: {a.detail}</span>
                      <Link className="ml-auto text-navy-800 underline" to={m.link}>Open {m.link.slice(1)}</Link>
                    </li>
                  )
                })}
              </ul>
            )}
          </section>
        </>
      )}
    </div>
  )
}
