function Box({ x, y, w, h, title, lines = [], fill = '#ffffff' }: { x: number; y: number; w: number; h: number; title: string; lines?: string[]; fill?: string }) {
  return (
    <g>
      <rect x={x} y={y} width={w} height={h} rx={8} fill={fill} stroke="#13315c" strokeWidth={1.5} />
      <text x={x + w / 2} y={y + 20} textAnchor="middle" fontSize={13} fontWeight={700} fill="#0b2545">{title}</text>
      {lines.map((l, i) => <text key={i} x={x + w / 2} y={y + 38 + i * 15} textAnchor="middle" fontSize={11} fill="#1e293b">{l}</text>)}
    </g>
  )
}
function Arrow({ x1, y1, x2, y2 }: { x1: number; y1: number; x2: number; y2: number }) {
  return <line x1={x1} y1={y1} x2={x2} y2={y2} stroke="#13315c" strokeWidth={2} markerEnd="url(#arr)" />
}

