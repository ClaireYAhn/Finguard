import { useState } from 'react'
import { api } from '../api'
import { AuditDetailDrawer } from '../components/AuditDetail'
import { ActionChip, ChannelBadge, Empty, ErrorBox, PageHeader, Spinner, Table, Th } from '../components/ui'
import { fmtTime, useFetch } from '../hooks'
import type { AuditRecord } from '../types'

export function RuleChips({ r }: { r: AuditRecord }) {
  const fired = (r.rule_results || []).filter((x) => x.status !== 'pass')
  if (!fired.length) return <span className="text-slate-700">none</span>
  return <div className="flex flex-wrap gap-1">{fired.map((x, i) => <span key={i} className="chip bg-slate-100 font-mono text-slate-900 ring-1 ring-slate-400">{x.rule_id}</span>)}</div>
}

export function AuditRows({ rows, onOpen }: { rows: AuditRecord[]; onOpen: (r: AuditRecord) => void }) {
  return (
    <Table caption="Audit records. Activate a row's time link to open details.">
      <thead><tr><Th>Time</Th><Th>App</Th><Th>User</Th><Th>Role</Th><Th>Channel</Th><Th>Action</Th><Th>Rules fired</Th><Th>Latency</Th><Th>Engine</Th></tr></thead>
      <tbody className="divide-y divide-slate-200">
        {rows.map((r) => (
          <tr key={r.id} className="cursor-pointer hover:bg-navy-50" onClick={() => onOpen(r)}>
            <td className="td whitespace-nowrap"><button type="button" className="text-navy-800 underline" onClick={(e) => { e.stopPropagation(); onOpen(r) }}>{fmtTime(r.ts)}</button></td>
            <td className="td">{r.app_name}</td><td className="td">{r.user}</td><td className="td">{r.role}</td>
            <td className="td"><ChannelBadge channel={r.channel} /></td>
            <td className="td"><ActionChip action={r.final_action} /></td>
            <td className="td"><RuleChips r={r} /></td>
            <td className="td whitespace-nowrap">{r.latency?.total_ms !== undefined ? `${Number(r.latency.total_ms).toFixed(0)} ms` : 'n/a'}</td>
            <td className="td">{r.engine}</td>
          </tr>
        ))}
      </tbody>
    </Table>
  )
}

export default function Live() {
  const [paused, setPaused] = useState(false)
  const [sel, setSel] = useState<AuditRecord | null>(null)
  const q = useFetch<AuditRecord[]>('live', () => api('/api/audit?limit=50'), { interval: 3000, paused })
  return (
    <div>
      <PageHeader title="Live traffic">
        <button type="button" className="btn-secondary" aria-pressed={paused} onClick={() => setPaused(!paused)}>{paused ? 'Resume refresh' : 'Pause refresh'}</button>
      </PageHeader>
      <p className="mb-3 text-sm text-slate-800" aria-live="polite">{paused ? 'Auto-refresh is paused.' : 'Refreshing every 3 seconds.'} Rows marked <span className="chip bg-orange-100 text-orange-950 ring-1 ring-orange-700">Simulated traffic</span> were generated by the simulator.</p>
      {q.error && <ErrorBox message={q.error} onRetry={q.reload} />}
      {q.loading && <Spinner />}
      {q.data && q.data.length === 0 && <Empty>No traffic yet. Send a request through the gateway or generate simulated traffic from the Overview page.</Empty>}
      {q.data && q.data.length > 0 && <AuditRows rows={q.data} onOpen={setSel} />}
      {sel && <AuditDetailDrawer id={sel.id} preview={sel} onClose={() => setSel(null)} />}
    </div>
  )
}
